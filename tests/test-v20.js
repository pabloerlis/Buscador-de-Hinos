'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const base=path.join(__dirname,'../app/src/main/assets');
const read=x=>fs.readFileSync(path.join(base,x),'utf8');
const source={console,JSON,Map,Set,Number,Math,Array,String,RegExp,Object};vm.createContext(source);
for(const p of ['scripture-index.js','semantic-engine.js','bible-graph-engine.js'])vm.runInContext(read(p),source,{filename:p});
const Scripture=vm.runInContext('ScriptureIndex',source);
const Graph=vm.runInContext('BibleGraphEngine',source);
const Semantic=vm.runInContext('SemanticEngine',source);
const scripture=Scripture.create(JSON.parse(read('scripture-pt.json')));
const semantic=Semantic.create(JSON.parse(read('semantic-db.json')));
const stories=JSON.parse(read('bible-narratives.json'));
assert.equal(stories.narratives.length,48);
const sampleGraph={schema_version:1,revision:'test',t:{},x:{},narratives:stories.narratives,
 stats:{topics_read:5745,topic_links:12000,crossref_links:343610}};
for(let i=25;i<=34;i++)sampleGraph.t['Mark.5.'+i]=i<28?['cura']:['cura','fe'];
sampleGraph.t['Matt.9.20']=['cura','fe'];sampleGraph.t['Luke.8.48']=['fe','paz'];
sampleGraph.t['John.3.16']=['amor','salvacao','vida_eterna'];
sampleGraph.t['Ps.23.1']=['confianca','protecao'];
sampleGraph.x['Mark.5.25']=[['Matt.9.20',24],['Luke.8.48',18]];
const graph=Graph.create(sampleGraph,scripture,semantic);
const a=graph.resolve('Marcos 5:25-34');
assert.equal(a.reference,'Marcos 5:25-34');
assert.equal(a.verses,10);
assert.ok(a.concepts.some(x=>x.id==='cura'));
assert.ok(a.concepts.some(x=>x.id==='fe'));
assert.ok(a.relatedCount>0);
const alias=graph.resolve('Mulher do fluxo de sangue');
assert.equal(alias.reference,'Marcos 5:25-34');
assert.equal(alias.narrative,'Mulher do fluxo de sangue');
assert.ok(alias.concepts.length>0);
const alias2=graph.resolve('mulher que tocou em JESUS');
assert.equal(alias2.reference,'Marcos 5:25-34');
const disabled=graph.resolve('Marcos 5:25-34',{bibleGraph:false});
assert.equal(disabled,null);
const withoutLinks=graph.resolve('Marcos 5:25-34',{bibleLinks:false});
assert.equal(withoutLinks.relatedCount,0);
const good={title:'Cristo me curou',lyrics:'Pela fé fui curado, teu poder me restaurou, confio no senhor e encontro paz.',semantic_profile:[{id:'fe',label:'Fé'},{id:'cura',label:'Cura'}]};
const wrong={title:'Filho de Deus',lyrics:'O Filho de Deus veio para me dar alegria, cantemos um louvor.',semantic_profile:[{id:'alegria',label:'Alegria'}]};
const rGood=graph.evaluate(good,a),rWrong=graph.evaluate(wrong,a);
assert.ok(rGood.score>=12,rGood.score);
assert.ok(rGood.score>rWrong.score+12,`${rGood.score} vs ${rWrong.score}`);
assert.ok(rGood.reasons.some(x=>x.includes('Passagem Marcos')));
const j=graph.resolve('João 3:16');assert.equal(j.reference,'João 3:16');
assert.ok(j.concepts.some(x=>x.id==='amor'));
const p=graph.resolve('Salmo 23:1');assert.ok(p.concepts.some(x=>x.id==='protecao'));
const chapter=graph.resolve('Marcos 5');assert.ok(chapter?.verses>=25);
const malformed=graph.resolve('123 999:999');assert.equal(malformed,null);
const html=read('index.html'),api=read('offline-api.js'),app=read('app.js');
assert.match(html,/bible-graph-engine\.js/);assert.match(html,/id="bible-graph-toggle"/);
assert.match(html,/id="bible-depth"/);assert.match(html,/id="settings-bible-graph"/);
assert.match(api,/bibleGraph\.evaluate\(song,graphCtx\)/);
assert.match(api,/bible_graph_ready/);
assert.match(app,/bibleGraph:'bible-graph-toggle'/);
assert.match(app,/ScriptureIndex\.parse\(query\)/);
const workflow=fs.readFileSync(path.join(__dirname,'../.github/workflows/android-apk.yml'),'utf8');
assert.match(workflow,/scripts\/build_bible_graph\.py/);
assert.ok(/node tests\/test-v20\.js/.test(workflow) || /for test in tests\/test-\*\.js/.test(workflow),
  'O pipeline deve executar o teste v2.0 explicitamente ou descobrir todos os testes automaticamente.');
const program=fs.readFileSync(path.join(__dirname,'../scripts/build_bible_graph.py'),'utf8');
assert.match(program,/topics_read/);assert.match(program,/crossref_links/);
console.log('v2.0: referências, narrativas, pontuação, falsos positivos, opções e build verificados (30+ assertivas).');
