'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const values=new Map(),styles=new Map();
const root={dataset:{},style:{setProperty(k,v){styles.set(k,v)}}};
const document={documentElement:root,querySelector:()=>null,getElementById:()=>null,readyState:'complete'};
const media={matches:false,addEventListener(){}};
const env={document,window:{},matchMedia:()=>media,localStorage:{getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)}};
const src=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/appearance.js'),'utf8');
const make=()=>vm.runInNewContext(src+'\nAppearance',env);
let api=make();
assert.equal(root.dataset.palette,'emerald');
api.update({palette:'ocean',mode:'dark',motion:'zoom',speed:'slow'});
assert.equal(root.dataset.theme,'dark');assert.equal(root.dataset.palette,'ocean');
assert.equal(root.dataset.motion,'zoom');assert.equal(api.duration(),390);
assert.equal(styles.get('--header-a'),'#163b66');
api=make();assert.equal(api.settings().palette,'ocean');assert.equal(api.settings().mode,'dark');
api.update({palette:'invalid',mode:'bad',motion:'bad',speed:'bad'});
assert.equal(api.settings().palette,'emerald');assert.equal(api.settings().mode,'system');
api.update({motion:'none'});assert.equal(api.duration(),0);
api.update({motion:'slide',speed:'fast'});assert.equal(api.duration(),150);
media.matches=true;api.update({mode:'system'});assert.equal(root.dataset.theme,'dark');assert.equal(api.duration(),0);
console.log('Aparência: paletas, tema, validação, persistência, duração e movimento reduzido aprovados.');
